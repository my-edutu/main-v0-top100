#!/usr/bin/env node
// Builds supabase/SETUP-ALL.sql — one ordered, re-runnable bootstrap you paste
// into the Supabase SQL editor to bring an empty/lagging database up to what
// the app expects.
//
// Why this exists: verified against the live project on 2026-07-27, every
// member-hub table (access_codes, user_notifications, member_features,
// dm_conversations, dm_messages, award_orders, feature_requests, interviews)
// was missing, and profiles had no membership_status column. Admin invite
// codes, signup, messaging, notifications and the whole award flow are all
// dead until these run — and they must run in dependency order, because the
// later files add foreign keys onto tables and columns the earlier ones create.
//
// This concatenates rather than restates the SQL, so there is exactly one
// source of truth per table and this file cannot drift from the migrations.
//
// Usage: node scripts/build-setup-sql.mjs

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const migrations = join(root, 'supabase', 'migrations')

// Dependency order. Everything here is idempotent (create ... if not exists,
// drop trigger/policy if exists, DO $$ ... EXCEPTION WHEN duplicate_object).
const ORDERED = [
  // 1. Member hub: profiles.membership_status + the columns everything else
  //    reads, access_codes, user_notifications, member_features, DMs.
  //    MUST be first — later files FK to profiles and filter on
  //    membership_status.
  'supabase/SETUP-MEMBER-HUB.sql',

  // 2. Standalone awardee-facing tables.
  'supabase/migrations/20260104_create_feature_requests.sql',

  // 3. Awards. FKs to public.profiles(id), so it follows the hub.
  'supabase/migrations/20260726_award_orders.sql',

  // 4. Impact interviews.
  'supabase/migrations/20260727_interviews.sql',
]

// Anything dated 20260728 or later is appended automatically in filename order,
// so new feature migrations join the bootstrap without editing this list.
const AUTO_FROM = '20260728'

// The date test must be anchored to an 8-digit prefix. A bare `name >=
// AUTO_FROM` string compare also matches undated files like
// `create_messages_table.sql`, because 'c' > '2' — which silently swept two
// unrelated legacy files into the bootstrap.
const DATED = /^(\d{8})_.*\.sql$/

function autoDiscovered() {
  if (!existsSync(migrations)) return []
  return readdirSync(migrations)
    .filter((name) => {
      const match = DATED.exec(name)
      return match !== null && match[1] >= AUTO_FROM
    })
    .sort()
    .map((name) => `supabase/migrations/${name}`)
}

const files = [...ORDERED, ...autoDiscovered()]

const banner = (text) => `\n${'-'.repeat(72)}\n-- ${text}\n${'-'.repeat(72)}\n`

let out = `-- =====================================================================
-- SETUP-ALL.sql — generated by scripts/build-setup-sql.mjs. DO NOT EDIT.
-- Regenerate with:  node scripts/build-setup-sql.mjs
--
-- Paste the whole file into the Supabase SQL editor and run it once. It is
-- idempotent: running it again is a no-op, so it is safe to re-run after
-- adding a migration.
--
-- Order matters. supabase/SETUP-MEMBER-HUB.sql must come first because it adds
-- profiles.membership_status and the member-hub tables that every later file
-- references.
-- =====================================================================
`

const missing = []
for (const relative of files) {
  const path = join(root, relative)
  if (!existsSync(path)) {
    missing.push(relative)
    continue
  }
  out += banner(`BEGIN ${relative}`)
  out += readFileSync(path, 'utf8').trimEnd()
  out += `\n${banner(`END ${relative}`)}`
}

if (missing.length) {
  // Loud, not silent: a bootstrap that quietly skips a file produces a database
  // that looks migrated and is not.
  console.error('ERROR: these files are listed in the build order but do not exist:')
  for (const name of missing) console.error(`  - ${name}`)
  process.exit(1)
}

writeFileSync(join(root, 'supabase', 'SETUP-ALL.sql'), out)
console.log(`Wrote supabase/SETUP-ALL.sql from ${files.length} file(s):`)
for (const name of files) console.log(`  - ${name}`)
