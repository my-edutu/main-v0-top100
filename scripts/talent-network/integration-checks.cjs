const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const sql = read('supabase/schema/talent-discovery.sql')
const required = ['talent_review_request','talent_review_claim','talent_finish_introduction','talent_record_outcome','talent_confirm_outcome','talent_record_application']
for (const routine of required) assert.match(sql, new RegExp(`function public\\.${routine}\\(`), `Missing transactional routine ${routine}`)
for (const file of ['components/talent/directory.tsx','components/talent/portfolio.tsx','components/talent/request-form.tsx','components/talent/admin-workspace.tsx','components/talent/introductions.tsx','app/api/admin/talent/route.ts','app/api/member/introductions/route.ts','app/for-organisations/page.tsx']) assert.ok(fs.existsSync(path.join(root,file)), `Missing integrated journey ${file}`)
assert.match(sql, /revoke all on public\.talent_public_directory from public,anon,authenticated/)
assert.match(sql, /talent_profiles where profile_id=p_actor for update/)
assert.match(sql, /p\.membership_status='approved'/)
console.log('Talent integration structure checks passed (not a substitute for database/browser tests).')
const crypto = require('node:crypto')
const homepage = read('app/page.tsx')
const originalHomepage = homepage
  .replace('import { TalentDiscoveryHomeSection } from "@/components/talent/homepage-sections"\n', '')
  .replace('import { talentDiscoveryEnabled } from "@/lib/talent/features"\n', '')
  .replace('        <TalentDiscoveryHomeSection />\n', '')
  .replace('<PartnershipHeroSection showTalentPipelines={talentDiscoveryEnabled()} />', '<PartnershipHeroSection />')
const body = Buffer.from(originalHomepage)
const blobSha = crypto.createHash('sha1').update(`blob ${body.length}\0`).update(body).digest('hex')
assert.equal(blobSha, '2d8b1aee0aa10fab5d3ee0e0a0cd82c465af4565', 'Homepage must preserve every byte of the pinned original outside the talent discovery integrations')
assert.match(read('app/awardees/[slug]/page.tsx'), /<StructuredData data={personSchema}/, 'Profiles must use the shared JSON-LD serializer')
assert.doesNotMatch(read('components/talent/portfolio.tsx'), /application\/ld\+json/, 'The portfolio must not emit duplicate profile markup')
assert.match(read('supabase/schema/talent-discovery-constraints.sql'), /\(published is null\) = \(published_revision is null\)/)
console.log('Homepage preservation and hardening structure checks passed.')
